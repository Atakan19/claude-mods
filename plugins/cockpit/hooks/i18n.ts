const TEXTS = { de, en }

// The system's locale, a first guess until the settings are read.
function localeLang(): Lang {
  try {
    return Intl.DateTimeFormat().resolvedOptions().locale.toLowerCase().startsWith('de') ? 'de' : 'en'
  } catch {
    return 'en'
  }
}

let lang: Lang = localeLang()

// The cockpit's own option wins; "auto" follows Claude Code's `language` setting, then the locale.
export function chooseLang(option: unknown, setting: unknown): Lang {
  if (option === 'de' || option === 'en') return option
  if (typeof setting === 'string' && setting.trim() !== '') return /^(de|german|deutsch)/i.test(setting.trim()) ? 'de' : 'en'
  return localeLang()
}

export function setLang(next: Lang) {
  lang = next
}

// The words in the language in force.
export const t = () => TEXTS[lang]
